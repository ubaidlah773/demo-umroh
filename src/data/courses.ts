// Helper functions for easy retrieval
export function getLessonsByApp(app: AppType): Lesson[] {
  return ALL_LESSONS.filter((lesson) => lesson.app === app);
}

export function getLessonsByAppAndLevel(app: AppType, level: LevelType): Lesson[] {
  return ALL_LESSONS.filter((lesson) => lesson.app === app && lesson.level === level);
}

export function getLessonByAppAndSlug(app: AppType, slug: string): Lesson | undefined {
  return ALL_LESSONS.find((lesson) => lesson.app === app && lesson.slug === slug);
}

export function getLessonById(id: string): Lesson | undefined {
  return ALL_LESSONS.find((lesson) => lesson.id === id);
}

export function getAdjacentLessons(currentId: string): { prev: Lesson | null; next: Lesson | null } {
  const index = ALL_LESSONS.findIndex((l) => l.id === currentId);
  if (index === -1) return { prev: null, next: null };
  const prev = index > 0 ? ALL_LESSONS[index - 1] : null;
  const next = index < ALL_LESSONS.length - 1 ? ALL_LESSONS[index + 1] : null;
  return { prev, next };
}
